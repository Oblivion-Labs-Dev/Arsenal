import type { TaskCardBorderTheme } from '@arsenal/ui';

export type ThemeUnlockRequirement =
  | { kind: 'level'; level: number }
  | {
      kind: 'achievement' | 'quest' | 'mastery' | 'seasonal' | 'path' | 'choice';
      label: string;
    };

export interface CosmeticThemeDefinition {
  id: TaskCardBorderTheme;
  name: string;
  description: string;
  lore: string;
  accent: string;
  secondary: string;
  collection: string;
  unlock: ThemeUnlockRequirement;
}

function theme(
  id: TaskCardBorderTheme,
  name: string,
  description: string,
  lore: string,
  accent: string,
  secondary: string,
  collection: string,
  unlock: ThemeUnlockRequirement,
): CosmeticThemeDefinition {
  return { id, name, description, lore, accent, secondary, collection, unlock };
}

