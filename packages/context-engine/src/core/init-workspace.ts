import { existsSync, mkdirSync, readFileSync, writeFileSync, appendFileSync } from "fs";
import { join } from "path";
import { ArsenalConfigSchema, DEFAULT_CONFIG } from "../schemas/arsenal-config.schema.js";
import { arsenalPath } from "../core/paths.js";
import { writeJsonFile, writeTextFile } from "../core/file-io.js";
import { ensureAnalyticsFiles } from "../analytics/analytics-store.js";
import {
  AGENTS_MD,
  CLAUDE_MD,
  CURSOR_RULES_MDC,
  ACTIVE_TASK_MD,
  ARCHITECTURE_MD,
  DECISIONS_MD,
  PITFALLS_MD,
  CONVENTIONS_MD,
  COMMANDS_MD,
  TESTING_RULES_MD,
  CONTEXT_POLICY_MD,
  CLAUDE_CONTEXT_MD,
  CURSOR_CONTEXT_MD,
  AGENT_HANDOFF_MD,
} from "../prompts/prompt-templates.js";

const ARSENAL_DIRS = [
  "summaries/files",
  "summaries/modules",
  "memory",
  "prompts",
  "rules",
  "cache",
];

export interface InitOptions {
  repoRoot?: string;
  force?: boolean;
}

export function ensureArsenalStructure(repoRoot: string): void {
  for (const dir of ARSENAL_DIRS) {
    mkdirSync(arsenalPath(repoRoot, dir), { recursive: true });
  }

  const configPath = arsenalPath(repoRoot, "config.json");
  if (!existsSync(configPath)) {
    writeJsonFile(configPath, DEFAULT_CONFIG);
  }

  writeTextIfMissing(arsenalPath(repoRoot, "summaries/architecture.md"), ARCHITECTURE_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "summaries/public-api.md"), "# Public API\n\n_Generated by summarize._\n");
  writeTextIfMissing(arsenalPath(repoRoot, "summaries/tests.md"), "# Tests\n\n_Generated by summarize._\n");
  writeTextIfMissing(arsenalPath(repoRoot, "memory/decisions.md"), DECISIONS_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "memory/pitfalls.md"), PITFALLS_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "memory/conventions.md"), CONVENTIONS_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "memory/active-task.md"), ACTIVE_TASK_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "memory/compact-history.md"), "# Compact History\n\n");
  writeTextIfMissing(arsenalPath(repoRoot, "prompts/claude-context.md"), CLAUDE_CONTEXT_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "prompts/cursor-context.md"), CURSOR_CONTEXT_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "prompts/agent-handoff.md"), AGENT_HANDOFF_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "rules/AGENTS.md"), AGENTS_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "rules/CLAUDE.md"), CLAUDE_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "rules/cursor-rules.md"), CURSOR_RULES_MDC.replace(/^---[\s\S]*?---\n\n/, ""));
  writeTextIfMissing(arsenalPath(repoRoot, "rules/testing-rules.md"), TESTING_RULES_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "rules/context-policy.md"), CONTEXT_POLICY_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "rules/commands.md"), COMMANDS_MD);
  writeTextIfMissing(arsenalPath(repoRoot, "cache/hashes.json"), "{}");
  writeTextIfMissing(arsenalPath(repoRoot, "cache/token-estimates.json"), "{}");
  ensureAnalyticsFiles(repoRoot);
}

export function initRepoRules(repoRoot: string): { created: string[]; skipped: string[] } {
  ensureArsenalStructure(repoRoot);

  const created: string[] = [];
  const skipped: string[] = [];

  const rootFiles: { path: string; content: string }[] = [
    { path: join(repoRoot, "AGENTS.md"), content: AGENTS_MD },
    { path: join(repoRoot, "CLAUDE.md"), content: CLAUDE_MD },
  ];

  for (const file of rootFiles) {
    if (existsSync(file.path)) {
      skipped.push(file.path);
    } else {
      writeTextFile(file.path, file.content);
      created.push(file.path);
    }
  }

  const cursorRulePath = join(repoRoot, ".cursor/rules/arsenal-context.mdc");
  mkdirSync(join(repoRoot, ".cursor/rules"), { recursive: true });
  if (existsSync(cursorRulePath)) {
    skipped.push(cursorRulePath);
  } else {
    writeTextFile(cursorRulePath, CURSOR_RULES_MDC);
    created.push(cursorRulePath);
  }

  ensureGitignore(repoRoot);

  return { created, skipped };
}

function writeTextIfMissing(path: string, content: string): void {
  if (!existsSync(path)) {
    writeTextFile(path, content);
  }
}

function ensureGitignore(repoRoot: string): void {
  const gitignorePath = join(repoRoot, ".gitignore");
  const entry = ".arsenal/cache/";
  if (!existsSync(gitignorePath)) {
    writeFileSync(gitignorePath, `${entry}\n`, "utf-8");
    return;
  }
  const content = readFileSync(gitignorePath, "utf-8");
  if (!content.includes(".arsenal/cache")) {
    appendFileSync(gitignorePath, `\n${entry}\n`, "utf-8");
  }
}

export function loadConfig(repoRoot: string) {
  const path = arsenalPath(repoRoot, "config.json");
  if (!existsSync(path)) return DEFAULT_CONFIG;
  return ArsenalConfigSchema.parse(JSON.parse(readFileSync(path, "utf-8")));
}
